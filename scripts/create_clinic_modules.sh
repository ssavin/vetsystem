#!/bin/bash
# Генератор модулей для каждой клиники

generate_module() {
  local CLINIC_NAME="$1"
  local HOST="$2"
  local PORT="$3"
  local DB="$4"
  local USER="$5"
  local PASS="$6"
  local FILENAME="$7"

cat > "/home/runner/workspace/scripts/${FILENAME}" << EOF
// =====================================================================
// ВНЕШНЯЯ ОБРАБОТКА 1С: Отчёт о розничных продажах — ${CLINIC_NAME}
// =====================================================================
// Подключение к базе зашито внутри. Просто выберите период и создайте документ.
//
// КАК СОЗДАТЬ В КОНФИГУРАТОРЕ:
// 1. Файл → Новый → Внешняя обработка
// 2. Добавить форму (Формы → Добавить → Основная: ДА)
// 3. Реквизиты формы:
//    Имя                    Тип
//    ─────────────────────────────────────────────────
//    ДатаС                  Дата
//    ДатаПо                 Дата
//    Организация            СправочникСсылка.Организации
//    Склад                  СправочникСсылка.Склады
//    НоменклатураУслуги     СправочникСсылка.Номенклатура
//    НоменклатураТовары     СправочникСсылка.Номенклатура
//    СтавкаНДС              ПеречислениеСсылка.СтавкиНДС
//    РезультатОтчета        Строка(500)
// 4. Элементы формы:
//    [Поле даты]   ДатаС             "Период с"
//    [Поле даты]   ДатаПо            "по"
//    [Поле выбора] Организация       "Организация"
//    [Поле выбора] Склад             "Склад"
//    [Поле выбора] НоменклатураУслуги "Номенклатура: услуги"
//    [Поле выбора] НоменклатураТовары "Номенклатура: товары"
//    [Поле выбора] СтавкаНДС         "Ставка НДС"
//    [Кнопка]      команда СформироватьОтчет "Создать документ в 1С"
//    [Поле текста] РезультатОтчета   "Результат" (только чтение)
// =====================================================================

// Параметры подключения (изменять не нужно)
Перем VETAIS_HOST Экспорт;
Перем VETAIS_PORT Экспорт;
Перем VETAIS_DB   Экспорт;
Перем VETAIS_USER Экспорт;
Перем VETAIS_PASS Экспорт;

#Область ОбработчикиСобытийФормы

&НаСоздании
Процедура ПриСозданииНаСервере(Отказ, СтандартнаяОбработка)
	ДатаС  = НачалоМесяца(ДобавитьМесяц(ТекущаяДата(), -1));
	ДатаПо = КонецМесяца(ДобавитьМесяц(ТекущаяДата(), -1));
	СтавкаНДС  = Перечисления.СтавкиНДС.БезНДС;
	Организация = ПервыйЭлементСправочника("Организации");
КонецПроцедуры

&НаСервере
Функция ПервыйЭлементСправочника(ИмяСправочника)
	Выборка = Справочники[ИмяСправочника].Выбрать();
	Если Выборка.Следующий() Тогда Возврат Выборка.Ссылка; КонецЕсли;
	Возврат Справочники[ИмяСправочника].ПустаяСсылка();
КонецФункции

#КонецОбласти

#Область ОбработчикиКомандФормы

&НаКлиенте
Процедура СформироватьОтчет(Команда)
	Если Не ЗначениеЗаполнено(ДатаС) Или Не ЗначениеЗаполнено(ДатаПо) Тогда
		Сообщить("Укажите период!", СтатусСообщения.Важное); Возврат;
	КонецЕсли;
	Если Не ЗначениеЗаполнено(Организация) Тогда
		Сообщить("Укажите организацию!", СтатусСообщения.Важное); Возврат;
	КонецЕсли;
	Если Не ЗначениеЗаполнено(НоменклатураУслуги) И Не ЗначениеЗаполнено(НоменклатураТовары) Тогда
		Сообщить("Укажите номенклатуру для услуг и/или товаров!", СтатусСообщения.Важное); Возврат;
	КонецЕсли;

	РезультатОтчета = "Выполняется запрос к базе...";
	Результат = СоздатьДокумент(ДатаС, КонецДня(ДатаПо), Организация, Склад,
		НоменклатураУслуги, НоменклатураТовары, СтавкаНДС);
	РезультатОтчета = Результат.Сообщение;
	Если Результат.Успех Тогда
		ПоказатьЗначение(, Результат.ДокументСсылка);
	КонецЕсли;
КонецПроцедуры

#КонецОбласти

#Область СлужебныеПроцедурыИФункции

&НаСервереБезКонтекста
Функция ПолучитьДанныеВетаис(ДатаОт, ДатаДо)

	Строка = "Driver={PostgreSQL ANSI(x64)};"
		+ "Server=${HOST};Port=${PORT};Database=${DB};"
		+ "Uid=${USER};Pwd=${PASS};"
		+ "UseServerSidePrepare=0;Sslmode=disable;";

	ДатОт = Формат(ДатаОт, "ДФ=yyyy-MM-dd");
	ДатДо = Формат(ДатаДо, "ДФ=yyyy-MM-dd");

	SQL = "WITH t AS ("
		+ " SELECT sum(ai.sum_with_vat) FILTER (WHERE it.id_type=1) AS tov,"
		+ "        sum(ai.sum_with_vat) FILTER (WHERE it.id_type=2) AS usl,"
		+ "        sum(ai.sum_with_vat) AS ito"
		+ " FROM accounts_items ai"
		+ " JOIN accounts_headers ah ON ah.id=ai.account_header_id"
		+ " LEFT JOIN items_type it ON it.id=ai.item_type_id"
		+ " WHERE ai.deleted=0 AND ah.deleted=0"
		+ "   AND ah.datetime_create::date BETWEEN '" + ДатОт + "' AND '" + ДатДо + "'"
		+ ") SELECT round(coalesce(ito,0)::numeric,2) AS ito,"
		+ "         round(coalesce(usl,0)::numeric,2) AS usl,"
		+ "         round(coalesce(tov,0)::numeric,2) AS tov FROM t";

	Рез = Новый Структура("Успех,Итого,Услуги,Товары,Ошибка", Ложь, 0, 0, 0, "");
	Попытка
		Conn = Новый COMОбъект("ADODB.Connection");
		Conn.ConnectionString = Строка;
		Conn.CursorLocation  = 3;
		Conn.Open();
		Cmd = Новый COMОбъект("ADODB.Command");
		Cmd.ActiveConnection = Conn;
		Cmd.CommandText      = SQL;
		Cmd.CommandTimeout   = 60;
		Rs = Cmd.Execute();
		Если Не Rs.EOF Тогда
			Рез.Итого   = Rs.Fields.Item("ito").Value;
			Рез.Услуги  = Rs.Fields.Item("usl").Value;
			Рез.Товары  = Rs.Fields.Item("tov").Value;
			Рез.Успех   = Истина;
		КонецЕсли;
		Rs.Close(); Conn.Close();
	Исключение
		Рез.Ошибка = "ОШИБКА ПОДКЛЮЧЕНИЯ:" + Символы.ПС + ОписаниеОшибки()
			+ Символы.ПС + "Проверьте psqlODBC: https://www.postgresql.org/ftp/odbc/versions/msi/";
	КонецПопытки;
	Возврат Рез;
КонецФункции

&НаСервереБезКонтекста
Функция СоздатьДокумент(ДатаОт, ДатаДо, Организация, Склад,
	НоменклатураУслуги, НоменклатураТовары, СтавкаНДС)

	Рез = Новый Структура("Успех,Сообщение,ДокументСсылка", Ложь, "", Неопределено);

	Данные = ПолучитьДанныеВетаис(ДатаОт, ДатаДо);
	Если Не Данные.Успех Тогда Рез.Сообщение = Данные.Ошибка; Возврат Рез; КонецЕсли;
	Если Данные.Итого = 0 Тогда Рез.Сообщение = "Нет данных за период"; Возврат Рез; КонецЕсли;

	ДатОт = Формат(ДатаОт, "ДФ=yyyy-MM-dd");
	ДатДо = Формат(ДатаДо, "ДФ=yyyy-MM-dd");

	Попытка
		Д = Документы.ОтчетОРозничныхПродажах.СоздатьДокумент();
		Д.Дата        = ДатаДо;
		Д.Организация = Организация;
		Если ЗначениеЗаполнено(Склад) Тогда Д.Склад = Склад; КонецЕсли;
		Д.Комментарий = "Vetais ${CLINIC_NAME}: " + ДатОт + " — " + ДатДо
			+ " | итого: " + Данные.Итого;

		Если ЗначениеЗаполнено(НоменклатураУслуги) И Данные.Услуги > 0 Тогда
			Стр = Д.Товары.Добавить();
			Стр.Номенклатура = НоменклатураУслуги;
			Стр.Количество   = 1;
			Стр.Цена         = Данные.Услуги;
			Стр.Сумма        = Данные.Услуги;
			Стр.СтавкаНДС    = СтавкаНДС;
			Стр.СуммаНДС     = 0;
		КонецЕсли;

		Если ЗначениеЗаполнено(НоменклатураТовары) И Данные.Товары > 0 Тогда
			Стр = Д.Товары.Добавить();
			Стр.Номенклатура = НоменклатураТовары;
			Стр.Количество   = 1;
			Стр.Цена         = Данные.Товары;
			Стр.Сумма        = Данные.Товары;
			Стр.СтавкаНДС    = СтавкаНДС;
			Стр.СуммаНДС     = 0;
		КонецЕсли;

		Д.Записать(РежимЗаписиДокумента.Запись);
		Рез.Успех          = Истина;
		Рез.ДокументСсылка = Д.Ссылка;
		Рез.Сообщение      =
			"✅ Документ создан!" + Символы.ПС +
			"Период:  " + ДатОт + " — " + ДатДо + Символы.ПС +
			"Итого:   " + Данные.Итого  + " руб." + Символы.ПС +
			"Услуги:  " + Данные.Услуги + " руб." + Символы.ПС +
			"Товары:  " + Данные.Товары + " руб." + Символы.ПС + Символы.ПС +
			"Документ открыт для проверки. Проведите вручную.";
	Исключение
		Рез.Сообщение = "ОШИБКА СОЗДАНИЯ ДОКУМЕНТА:" + Символы.ПС + ОписаниеОшибки();
	КонецПопытки;
	Возврат Рез;
КонецФункции

#КонецОбласти
EOF
  echo "Создан: ${FILENAME}"
}

generate_module "Probiko"  "localhost"       "5432" "vetais_probiko_local" "postgres" "ASPI6rin" "1c_retail_report_PROBIKO.bsl"
generate_module "Алисавет" "45.128.206.134"  "5454" "vetais_alisavet"      "postgres" "ASPI6rin" "1c_retail_report_ALISAVET.bsl"
generate_module "Динго"    "109.173.124.18"  "5454" "vetais"               "postgres" "vetais"   "1c_retail_report_DINGO.bsl"
generate_module "Василёк"  "94.198.53.52"    "5454" "vetais_vasilek"       "postgres" "vetais"   "1c_retail_report_VASILEK.bsl"

echo "Готово!"
